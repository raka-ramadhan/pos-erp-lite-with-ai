interface SidebarProps {
  isOpen: boolean;
  onClose: () => void;
  isCollapsed?: boolean;
  onToggleCollapse?: () => void;
}

interface NavItemProps {
  item: MenuItem;
  isCollapsed: boolean;
  depth?: number;
  // Navigation state from parent
  expandedIds: Set<string>;
  onToggle: (id: string) => void;
}

function NavItem({
  item,
  isCollapsed,
  depth = 0,
  expandedIds,
  onToggle,
}: NavItemProps) {
  const location = useLocation();
  const hasChildren = item.children && item.children.length > 0;
  const isActive = location.pathname === item.path;

  // Check if this menu has an active descendant
  const hasActiveDescendant = hasChildren && (
    item.children?.some(child => child.path === location.pathname) ||
    item.children?.some(child =>
      child.children?.some(grandChild => grandChild.path === location.pathname)
    )
  );

  // Determine if this item should be expanded
  // Priority: has active descendant > route active child > user manually expanded
  const shouldBeExpanded = expandedIds.has(item.id) || hasActiveDescendant;

  // Render icon if available
  const IconComponent = item.icon ? iconMap[item.icon] : null;

  // Don't render menu items without paths in collapsed mode
  if (isCollapsed && !item.path) {
    return null;
  }

  // Calculate indentation based on depth
  const indentClass = depth > 0 ? `ml-${Math.min(depth * 4, 12)}` : '';

  // For GROUP type, render as expandable header
  if (item.type === 'GROUP' && hasChildren) {
    return (
      <div className="relative">
        {/* Active indicator line */}
        {hasActiveDescendant && (
          <div className="absolute left-0 top-1 bottom-1 w-0.5 bg-indigo-600 rounded-full" />
        )}

        <button
          onClick={() => onToggle(item.id)}
          className={cn(
            'w-full flex items-center justify-between px-3 py-2.5 rounded-lg transition-all duration-200',
            'text-slate-600 hover:bg-slate-50 hover:text-slate-900',
            hasActiveDescendant && 'bg-indigo-50/50 text-indigo-700',
            !isCollapsed && indentClass
          )}
        >
          <div className="flex items-center gap-3">
            {IconComponent && (
              <span className={cn(hasActiveDescendant && 'text-indigo-600')}>
                <IconComponent />
              </span>
            )}
            {!isCollapsed && (
              <span className={cn(
                'font-medium text-sm',
                hasActiveDescendant && 'text-indigo-700'
              )}>
                {item.name}
              </span>
            )}
          </div>
          {!isCollapsed && (
            <ChevronRight
              className={cn(
                'w-4 h-4 text-slate-400 transition-transform duration-200',
                shouldBeExpanded && 'rotate-90'
              )}
            />
          )}
        </button>

        {/* Animated children container */}
        {!isCollapsed && (
          <AnimatePresence initial={false}>
            {shouldBeExpanded && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: 'auto', opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                transition={{ duration: 0.2, ease: 'easeInOut' }}
                className="overflow-hidden"
              >
                <div className={cn('mt-1 space-y-0.5', depth > 0 ? `ml-4` : 'ml-3')}>
                  {item.children?.map((child) => (
                    <NavItem
                      key={child.id}
                      item={child}
                      isCollapsed={isCollapsed}
                      depth={depth + 1}
                      expandedIds={expandedIds}
                      onToggle={onToggle}
                    />
                  ))}
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        )}
      </div>
    );
  }

  // For MENU/LINK type with path
  if (item.path) {
    return (
      <Link
        to={item.path}
        className={cn(
          'relative flex items-center gap-3 px-3 py-2.5 rounded-lg transition-all duration-200',
          'hover:bg-slate-50',
          isActive
            ? 'bg-indigo-50 text-indigo-600 font-medium'
            : 'text-slate-600 hover:text-slate-900',
          isCollapsed && 'justify-center px-2',
          !isCollapsed && indentClass
        )}
      >
        {/* Active indicator */}
        {isActive && (
          <div className="absolute left-0 top-1 bottom-1 w-0.5 bg-indigo-600 rounded-full" />
        )}

        {IconComponent && (
          <span className={cn(isActive ? 'text-indigo-600' : 'text-slate-400')}>
            <IconComponent />
          </span>
        )}
        {!isCollapsed && (
          <span className="font-medium text-sm">{item.name}</span>
        )}
      </Link>
    );
  }

  // Fallback
  return null;
}

export function DynamicSidebar({
  isOpen,
  onClose,
  isCollapsed = false,
  onToggleCollapse,
}: SidebarProps) {
  const { data: menus, isLoading, error } = useSidebar();
  const { expandedIds, toggle } = useSidebarNavigation(menus);

  const sidebarContent = (
    <div className={cn(
      'flex flex-col h-full bg-white border-r border-slate-200 transition-all duration-300',
      isCollapsed ? 'w-20' : 'w-64'
    )}>
      {/* Logo */}
      <div className="flex items-center justify-between p-4 border-b border-slate-200">
        {!isCollapsed && (
          <div className="flex items-center gap-3">
            <Logo size="md" />
            <span className="font-bold text-xl text-slate-900">Nexus</span>
          </div>
        )}
        {isCollapsed && <Logo size="sm" />}

        {/* Collapse toggle - desktop only */}
        <button
          onClick={onToggleCollapse}
          className="hidden lg:flex items-center justify-center w-8 h-8 rounded-lg hover:bg-slate-100 transition-colors"
          aria-label={isCollapsed ? 'Expand sidebar' : 'Collapse sidebar'}
        >
          <ChevronLeft className={cn(
            'w-5 h-5 text-slate-500 transition-transform duration-200',
            isCollapsed && 'rotate-180'
          )} />
        </button>
      </div>

      {/* Navigation */}
      <nav className="flex-1 p-4 space-y-1 overflow-y-auto">
        {isLoading ? (
          <div className="space-y-2">
            {[1, 2, 3, 4, 5].map((i) => (
              <div
                key={i}
                className="h-10 bg-slate-100 rounded-lg animate-pulse"
              />
            ))}
          </div>
        ) : error ? (
          <div className="p-3 text-sm text-red-600 bg-red-50 rounded-lg">
            Failed to load menu
          </div>
        ) : menus && menus.length > 0 ? (
          menus.map((item) => (
            <NavItem
              key={item.id}
              item={item}
              isCollapsed={isCollapsed}
              depth={0}
              expandedIds={expandedIds}
              onToggle={toggle}
            />
          ))
        ) : (
          <p className="text-sm text-slate-500 text-center py-4">
            No menu items available
          </p>
        )}
      </nav>

      {/* Footer */}
      <div className="p-4 border-t border-slate-200">
        {!isCollapsed && (
          <p className="text-xs text-slate-400 text-center">
            Nexus Admin v1.0.0
          </p>
        )}
      </div>
    </div>
  );

  return (
    <>
      {/* Mobile Overlay */}
      {isOpen && (
        <div
          className="fixed inset-0 bg-black/50 z-40 lg:hidden"
          onClick={onClose}
          aria-hidden="true"
        />
      )}

      {/* Mobile Drawer */}
      <div className={cn(
        'fixed inset-y-0 left-0 z-50 lg:hidden transform transition-transform duration-300',
        isOpen ? 'translate-x-0' : '-translate-x-full'
      )}>
        {sidebarContent}

        {/* Close button */}
        <button
          onClick={onClose}
          className="absolute top-4 right-4 lg:hidden flex items-center justify-center w-8 h-8 rounded-lg bg-slate-100 hover:bg-slate-200 transition-colors"
          aria-label="Close sidebar"
        >
          <X className="w-5 h-5 text-slate-500" />
        </button>
      </div>

      {/* Desktop Sidebar */}
      <div className="hidden lg:block">
        {sidebarContent}
      </div>
    </>
  );
}
